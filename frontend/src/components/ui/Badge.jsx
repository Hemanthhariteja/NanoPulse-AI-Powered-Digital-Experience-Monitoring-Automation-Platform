import { humanize } from '../../lib/format';

const TONES = {
  healthy: 'bg-healthy-soft text-healthy',
  warning: 'bg-warning-soft text-warning',
  critical: 'bg-critical-soft text-critical',
  offline: 'bg-offline-soft text-offline',
  info: 'bg-info-soft text-info',
  primary: 'bg-primary-soft text-primary-text',
  neutral: 'bg-surface-2 text-muted',
};

export function Badge({ tone = 'neutral', dot = false, children, className = '', title }) {
  return (
    <span title={title} className={`inline-flex items-center gap-1.5 rounded-full px-2 py-0.5 text-xs font-medium whitespace-nowrap ${TONES[tone]} ${className}`}>
      {dot && <span className="h-1.5 w-1.5 rounded-full bg-current" aria-hidden />}
      {children}
    </span>
  );
}

const DEVICE_TONE = { HEALTHY: 'healthy', WARNING: 'warning', CRITICAL: 'critical', OFFLINE: 'offline', PENDING: 'neutral' };
export const StatusBadge = ({ status }) => (
  <Badge tone={DEVICE_TONE[status] || 'neutral'} dot>
    {humanize(status || 'unknown')}
  </Badge>
);

const SEV_TONE = { CRITICAL: 'critical', WARNING: 'warning', INFO: 'info' };
export const SeverityBadge = ({ severity }) => <Badge tone={SEV_TONE[severity] || 'neutral'}>{humanize(severity)}</Badge>;

const INC_TONE = {
  NEW: 'info',
  INVESTIGATING: 'primary',
  PENDING_APPROVAL: 'warning',
  REMEDIATION_IN_PROGRESS: 'primary',
  RESOLVED: 'healthy',
  FAILED: 'critical',
};
export const IncidentStatusBadge = ({ status }) => <Badge tone={INC_TONE[status] || 'neutral'}>{humanize(status)}</Badge>;

const EXEC_TONE = {
  NOT_STARTED: 'neutral',
  QUEUED: 'info',
  RUNNING: 'primary',
  SUCCEEDED: 'healthy',
  FAILED: 'critical',
  TIMED_OUT: 'critical',
  CANCELLED: 'offline',
};
export const ExecutionBadge = ({ status }) => (
  <Badge tone={EXEC_TONE[status] || 'neutral'} dot={status === 'RUNNING' || status === 'QUEUED'}>
    {humanize(status)}
  </Badge>
);

const APPROVAL_TONE = { PENDING: 'warning', APPROVED: 'healthy', REJECTED: 'critical' };
export const ApprovalBadge = ({ status }) => <Badge tone={APPROVAL_TONE[status] || 'neutral'}>{humanize(status === 'PENDING' ? 'awaiting approval' : status)}</Badge>;

export const AgentTypeBadge = ({ agentType }) =>
  agentType === 'simulated' ? (
    <Badge tone="neutral" title="Virtual endpoint generated by the simulator">
      Simulated
    </Badge>
  ) : (
    <Badge tone="info" title="Real endpoint reporting through the Python agent">
      Real agent
    </Badge>
  );

export const ModeBadge = ({ mode }) =>
  mode ? <Badge tone={mode === 'SIMULATED' ? 'neutral' : 'info'}>{mode === 'SIMULATED' ? 'Simulated run' : 'Real execution'}</Badge> : null;
